"""Build the README result tables from results/results.csv and results/timing/.

Writes results/tables.md (Markdown). Every number in the README's results section is copied
from this file, so no number is typed by hand.

Usage (repo root):  python scripts/make_tables.py
"""

import csv
from pathlib import Path

RESULTS = Path("results/results.csv")
TIMING = Path("results/timing")
OUT = Path("results/tables.md")

# system id -> (display name, group); the order of GROUPS is the order of the legend
SYSTEMS = {
    "w2v2_xlsr_ft_kenlm": ("wav2vec2 XLS-R 300M fine-tuned + KenLM 3-gram", "ours"),
    "whisper_small_ft_beam5": ("Whisper-small fine-tuned, beam 5", "ours"),
    "whisper_small_ft_beam1": ("Whisper-small fine-tuned, beam 1", "ours"),
    "w2v2_xlsr_ft_greedy": ("wav2vec2 XLS-R 300M fine-tuned, greedy", "ours"),
    "whisper_large_v3_zeroshot": ("Whisper-large-v3, zero-shot", "published"),
    "whisper_small_zeroshot": ("Whisper-small, zero-shot", "published"),
    "anuragshas_w2v2_ur_lm": ("anuragshas XLS-R Urdu + its own LM", "published"),
    "anuragshas_w2v2_ur_greedy": ("anuragshas XLS-R Urdu, greedy", "published"),
    "kingabzpro_w2v2_urdu": ("kingabzpro wav2vec2 Urdu, greedy", "published"),
    "rnnt": ("ESPnet RNN-T", "baseline"),
    "gmm_hmm": ("Kaldi MFCC + GMM-HMM", "baseline"),
    "hybrid": ("ESPnet hybrid CTC/attention", "baseline"),
    "ctc": ("ESPnet CTC", "baseline"),
}
GROUPS = {"ours": "our fine-tuned system", "published": "published checkpoint, run as is",
          "baseline": "course baseline, trained by us"}


def pct(x):
    return f"{100 * float(x):.2f}%"


def load_results():
    rows = {}
    with RESULTS.open(encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            rows[(r["system"], r["split"])] = r  # a later row for the same pair replaces an earlier one
    return rows


def load_timing(system):
    path = TIMING / f"{system}.csv"
    if not path.exists():
        return None
    with path.open(encoding="utf-8") as fh:
        return next(csv.DictReader(fh))


def main():
    res = load_results()
    lines = ["# Result tables", "",
             "Generated by `scripts/make_tables.py` from `results/results.csv` and `results/timing/`. "
             "Do not edit by hand.", ""]

    lines += ["## Test set (3,031 clips, 9 unseen speakers), sorted by WER", "",
              "| # | System | Type | WER [95% CI] | CER | WER without the 1 overlapping sentence | RTF | Hardware |",
              "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    test = sorted((s for s in SYSTEMS if (s, "test") in res), key=lambda s: float(res[(s, "test")]["wer"]))
    for i, s in enumerate(test, 1):
        r, name, group = res[(s, "test")], *SYSTEMS[s]
        no = res.get((s, "test_nonoverlap"))
        t = load_timing(s)
        lines.append(f"| {i} | {name} | {GROUPS[group]} | {pct(r['wer'])} [{pct(r['wer_ci_low'])}, "
                     f"{pct(r['wer_ci_high'])}] | {pct(r['cer'])} | {pct(no['wer']) if no else '-'} | "
                     f"{float(t['rtf']):.4f} | {t['hardware']} |" if t else
                     f"| {i} | {name} | {GROUPS[group]} | {pct(r['wer'])} | {pct(r['cer'])} | - | - | - |")
    colab = res.get(("w2v2_xlsr_ft_greedy_colab", "test"))
    t = load_timing("w2v2_xlsr_ft_greedy_colab")
    if colab and t:
        lines += ["", f"The same greedy wav2vec2 model run again on Colab ({t['hardware']}), only to time "
                  f"greedy and LM decoding on the same GPU: WER {pct(colab['wer'])}, RTF {float(t['rtf']):.4f}."]

    lines += ["", "## Dev set (1,956 clips, 6 speakers)", "",
              "| System | WER [95% CI] | CER |", "| --- | --- | --- |"]
    for (s, split), r in res.items():
        if split == "dev":
            lines.append(f"| `{s}` | {pct(r['wer'])} [{pct(r['wer_ci_low'])}, {pct(r['wer_ci_high'])}] | {pct(r['cer'])} |")

    lines += ["", "## How much normalization matters (test)", "",
              "| System | No normalization | Letters and punctuation only | Full (main table) |",
              "| --- | --- | --- | --- |"]
    for s in SYSTEMS:
        cells = [res.get((s, k)) for k in ("test_nonorm", "test_nodigits", "test")]
        if cells[0] and cells[1]:
            lines.append(f"| {SYSTEMS[s][0]} | " + " | ".join(pct(c["wer"]) for c in cells) + " |")

    lm = Path("results/lm_tuning_dev.csv")
    if lm.exists():
        with lm.open(encoding="utf-8") as fh:
            grid = list(csv.DictReader(fh))
        lines += ["", "## KenLM weights chosen on dev (wav2vec2, beam 50)", "",
                  "| alpha | beta | dev WER | dev CER |", "| --- | --- | --- | --- |"]
        lines += [f"| {g['alpha']} | {g['beta']} | {pct(g['wer'])} | {pct(g['cer'])} |" for g in grid]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
